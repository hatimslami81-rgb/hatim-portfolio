const LANG_KEY = 'hatim-lang';

function getLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'ar' || saved === 'en') return saved;
  return 'en';
}

function t(key, lang = getLang()) {
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}

function applyLanguage(lang) {
  const dict = I18N[lang] || I18N.en;
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.body.classList.toggle('is-ar', lang === 'ar');
  localStorage.setItem(LANG_KEY, lang);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!dict[key]) return;

    // Reset split-text wrappers so translation can re-split
    if (el.classList.contains('split-text') && el.dataset.split !== 'brand') {
      el.textContent = dict[key];
      el.classList.remove('is-in');
      return;
    }

    if (el.classList.contains('btn') && el.querySelector(':scope > span')) {
      el.querySelector(':scope > span').textContent = dict[key];
      return;
    }

    // Education body with line break
    if (key === 'skills.eduBody') {
      const parts = dict[key].split('\n');
      el.innerHTML = `<strong>${parts[0]}</strong><br>${parts[1] || ''}`;
      return;
    }

    el.textContent = dict[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key]) el.innerHTML = dict[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.placeholder = dict[key];
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    if (dict[key]) el.setAttribute('aria-label', dict[key]);
  });

  // Page title
  const page = document.body.dataset.page;
  const titleKey = `meta.${page}.title`;
  if (dict[titleKey]) document.title = dict[titleKey];

  // Lang toggle: always show target language code (AR / EN)
  document.querySelectorAll('.lang-toggle').forEach((btn) => {
    btn.textContent = lang === 'ar' ? 'EN' : 'AR';
    btn.setAttribute('aria-label', dict['nav.langAria']);
  });

  // Cert list mixed content (span + text)
  document.querySelectorAll('[data-i18n-after]').forEach((el) => {
    const key = el.getAttribute('data-i18n-after');
    const label = el.querySelector('[data-i18n-label]');
    const textNode = [...el.childNodes].find((n) => n.nodeType === Node.TEXT_NODE);
    if (dict[key]) {
      // rebuild: keep label span, set remaining text
      const labelHtml = label ? label.outerHTML : '';
      el.innerHTML = `${labelHtml} ${dict[key]}`;
    }
  });

  document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}

function initI18n() {
  const lang = getLang();
  applyLanguage(lang);

  document.querySelectorAll('.lang-toggle').forEach((btn) => {
    btn.addEventListener('click', () => {
      const next = getLang() === 'ar' ? 'en' : 'ar';
      applyLanguage(next);
    });
  });
}

window.HatimI18n = { getLang, t, applyLanguage, initI18n, I18N };
